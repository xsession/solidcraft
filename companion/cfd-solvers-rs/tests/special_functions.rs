//! `core::erf`/`erfc` against glibc values (printed by CPython's `math`, which wraps libm).
use cfd_solvers::core::{erf, erfc};

#[test]
fn erf_and_erfc_match_libm() {
    for (x, c, e) in [
        (0.0, 1.0, 0.0),
        (0.1, 0.8875370839817152, 0.1124629160182849),
        (0.5, 0.4795001221869535, 0.5204998778130465),
        (1.0, 0.15729920705028513, 0.8427007929497149),
        (1.7, 0.016209541409225436, 0.9837904585907745),
        (1.99, 0.004888586800383003, 0.995111413199617),
        (2.0, 0.004677734981047265, 0.9953222650189527),
        (2.5, 0.0004069520174449589, 0.999593047982555),
        (3.3, 3.0577097964381654e-06, 0.9999969422902035),
        (5.0, 1.5374597944280351e-12, 0.9999999999984626),
        (8.0, 1.1224297172982928e-29, 1.0),
        (-1.2, 1.9103139782296354, -0.9103139782296353),
        (27.0, 5.23705e-319, 1.0),
    ] {
        let (rc, re): (f64, f64) = (erfc(x), erf(x));
        assert!(
            (rc - c).abs() <= 1e-14 * c.abs() + 1e-300,
            "erfc({x}) = {rc} vs {c}"
        );
        assert!(
            (re - e).abs() <= 2e-16 + 1e-15 * e.abs(),
            "erf({x}) = {re} vs {e}"
        );
    }
    assert!(erfc(f64::NAN).is_nan());
    assert_eq!(erfc(40.0), 0.0);
    assert_eq!(erfc(-40.0), 2.0);
}
